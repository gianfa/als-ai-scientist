#!/usr/bin/env bash
# Build the GitHub Pages site into website/_site.
# docs/ is the single source of truth for the content and website/ holds only the site's own sources. Quarto
# renders files inside its project directory only, so both are copied into a disposable build tree
# (website/.build, git-ignored) where the site sources sit beside the docs and every relative link resolves.
# Usage: website/build.sh [render|preview]  (default: render)
set -euo pipefail
cd "$(dirname "$0")"
[ -d ../docs ] || { echo "docs source not found: ../docs" >&2; exit 1; }
rm -rf .build _site
mkdir .build
cp -r ../docs/. .build/
cp _quarto.yml index.qmd paper.scss github-alerts.lua .build/
# The citation on the project page is CITATION.cff, rendered as BibTeX; index.qmd includes it. A broken or incomplete
# CITATION.cff stops the build rather than publishing a page without its citation.
"${PYTHON:-python3}" -I -B cff_citation.py ../CITATION.cff > .build/_citation.md
# The project page offers the technical report for download. The PDF is kept in ../reports/technical-report.pdf and
# is not generated by this build. Without it the site still builds, but the download button leads nowhere.
if [ -f ../reports/technical-report.pdf ]; then
    mkdir -p .build/assets/tech-report
    cp ../reports/technical-report.pdf .build/assets/tech-report/report.pdf
else
    echo "warning: reports/technical-report.pdf is missing; the report download will not work" >&2
fi
# Links from docs/ to repository files outside it (e.g. ../LICENSES.md) cannot be rendered: point them at GitHub.
REPO=https://github.com/gianfa/als-ai-scientist/blob/main
sed -i "s#](\.\./#](${REPO}/#g" .build/*.md
cd .build
quarto "${1:-render}"
